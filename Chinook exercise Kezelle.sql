-- 4. Write a query that returns `SupportRepId` and the number of customers assigned to each rep — name the count column `NumCustomers` — sorted by `NumCustomers` in descending order. 


SELECT 
	c.SupportRepId,
	c.CustomerId, 
	COUNT(*) AS NumCustomers
FROM customers c
GROUP BY c.SupportRepId
ORDER BY NumCustomers DESC;

-- 5. Write a query that returns `GenreId` and the average `UnitPrice` of tracks in that genre — name the average column `AvgPrice` — sorted by `AvgPrice` in descending order, limited to the top 5 rows. 

SELECT 
	t.GenreId,
	AVG(t.UnitPrice) AS AvgPrice
FROM tracks t
GROUP BY t.GenreId
ORDER BY AvgPrice DESC
LIMIT 5;

/*  Part B — Intermediate (Items 6-10)
1. Write a query that returns each genre's `Name` and the number of tracks in that genre — name the count column `NumTracks` — sorted by `NumTracks` in descending order, limited to the top 5 rows. 

*/

SELECT
	g.Name,
	COUNT (DISTINCT t.trackID) AS NumTracks
FROM genres g
LEFT JOIN tracks t
ON g.GenreID = t.GenreId 
GROUP BY g.Name 
ORDER BY NumTracks DESC
LIMIT 5;

