-- 3. Write a query that returns `FirstName`, `LastName`, the track name (named `TrackName`), `Quantity`, and `UnitPrice` from every invoice line ever billed to the customer with `CustomerId = 5`, sorted by `InvoiceLineId` in ascending order. 

SELECT 
	i.CustomerId,
	c.FirstName,
	c.LastName
	t.Name as TrackName,
	i.InvoiceID,
	ii.InvoiceLineID,
	ii.TrackID,
	t.UnitPrice
	
FROM customers c
LEFT JOIN invoices i ON c.CustomerId = i.CustomerId 
LEFT JOIN invoice_items ii ON i.InvoiceId = ii.InvoiceId
LEFT JOIN tracks t ON ii.TrackId = t.TrackId 
WHERE c.CustomerID = 5

-- 4. Write a query that returns the `Name` of each playlist and the number of tracks it contains — name the count column `NumTracks` — sorted by `NumTracks` in descending order. 

SELECT 
	p.Name
	COUNT (DISTINCT t.trackID) AS NumTracks
FROM playlists p
LEFT JOIN playlist_track pt ON pt.PlaylistId = p.PlaylistId
LEFT JOIN tracks t ON t.TrackID = pt.TrackId 
GROUP BY p.Name
ORDER BY NumTracks DESC;


